"""Host the spell relay and its temporary HTTPS Cloudflare Tunnel from this computer."""
import argparse
import hashlib
import json
import re
import secrets
import subprocess
import threading
import time
import urllib.request
from http.server import ThreadingHTTPServer
from pathlib import Path

from relay_server import RelayStore, handler_for_relay, load_secret

ROOT = Path(__file__).resolve().parent
VERSION = "2026.10.0"
BINARY_SHA256 = "86aee4017b26625cee8484c113558f48effa4cd47f7aa05fcf425604e5d2b23c"
DOWNLOAD = f"https://github.com/cloudflare/cloudflared/releases/download/{VERSION}/cloudflared-windows-amd64.exe"


def cloudflared():
    binary = ROOT.parent / "tools" / "cloudflared.exe"
    binary.parent.mkdir(exist_ok=True)
    if not binary.exists():
        print(f"Downloading official cloudflared {VERSION} once...", flush=True)
        urllib.request.urlretrieve(DOWNLOAD, binary)
    if hashlib.sha256(binary.read_bytes()).hexdigest() != BINARY_SHA256:
        raise RuntimeError("Cloudflare executable checksum failed. Remove companion/tools/cloudflared.exe and try again.")
    return binary


def write_config(url, server_token):
    # The credential is stored only in the host's ignored settings and Roblox's Secrets store.
    config = '-- Generated by HostRelay.cmd. Credential is in Roblox Secrets, never script source.\n'
    config += f'return {{ Enabled = true, Url = {json.dumps(url)}, SecretName = "VOICE_RELAY_SERVER_TOKEN" }}\n'
    (ROOT / "VoiceRelayConfig.generated.luau").write_text(config, encoding="utf-8")
    (ROOT.parent / "team-relay.json").write_text(json.dumps({"url": url}) + "\n", encoding="utf-8")
    repo_config = ROOT.parents[1] / "game/scripts/ServerScriptService/VoiceArena/VoiceRelayConfig.luau"
    if repo_config.parent.exists():
        repo_config.write_text(config, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", type=int, default=8790)
    args = parser.parse_args()
    binary = cloudflared()
    secret_path = ROOT / "relay.local.json"
    server_token = load_secret(secret_path)
    secrets_data = json.loads(secret_path.read_text())
    stop_token = secrets_data.setdefault("hostStopToken", secrets.token_urlsafe(48))
    secret_path.write_text(json.dumps(secrets_data) + "\n", encoding="utf-8")
    stopping = threading.Event()
    server = ThreadingHTTPServer(("127.0.0.1", args.port), handler_for_relay(RelayStore(), server_token, stopping.set, stop_token))
    server.daemon_threads = True
    threading.Thread(target=server.serve_forever, daemon=True).start()
    tunnel = None
    try:
        tunnel = subprocess.Popen([str(binary), "tunnel", "--no-autoupdate", "--protocol", "http2", "--url", f"http://127.0.0.1:{args.port}"],
                                  stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
                                  creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
        ready = threading.Event()
        log_path = ROOT / "tunnel.log"
        def output():
            with log_path.open("w", encoding="utf-8") as log:
                for line in tunnel.stdout:
                    log.write(line); log.flush()
                    match = re.search(r"https://[a-z0-9-]+\.trycloudflare\.com", line)
                    if match and not ready.is_set():
                        url = match.group(0)
                        write_config(url, server_token)
                        (ROOT / "host-state.json").write_text(json.dumps({"url": url, "port": args.port}) + "\n")
                        print(f"HTTPS RELAY: {url}", flush=True)
                        print("Keep this host running. Each player runs TeamTest.cmd and enters their own pairing code.", flush=True)
                        print("Studio server config: companion/bridge/VoiceRelayConfig.generated.luau (or the generated game module).", flush=True)
                        print("One-time setup: add VOICE_RELAY_SERVER_TOKEN in the game's Creator Dashboard Secrets. RelaySecretSetup.cmd copies the value for you.", flush=True)
                        print("If Studio is not syncing repo files, paste that module into ServerScriptService.VoiceArena.VoiceRelayConfig before Team Test.", flush=True)
                        ready.set()
        threading.Thread(target=output, daemon=True).start()
        deadline = time.monotonic() + 60
        while not ready.wait(0.5):
            if tunnel.poll() is not None:
                raise RuntimeError("HTTPS tunnel exited. Check companion/bridge/tunnel.log")
            if time.monotonic() > deadline:
                raise RuntimeError("HTTPS tunnel timed out. Check internet access and companion/bridge/tunnel.log")
        while not stopping.wait(1):
            if tunnel.poll() is not None:
                raise RuntimeError("HTTPS tunnel stopped. Restart HostRelay.cmd and update Studio with its new URL.")
    except KeyboardInterrupt:
        pass
    finally:
        if tunnel and tunnel.poll() is None:
            tunnel.terminate()
            try:
                tunnel.wait(timeout=5)
            except subprocess.TimeoutExpired:
                tunnel.kill()
        server.shutdown()
        server.server_close()
        print("Relay stopped.", flush=True)


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, OSError, ValueError) as error:
        print(f"Relay host error: {error}", flush=True)
        raise SystemExit(1)
